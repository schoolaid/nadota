<?php

use SchoolAid\Nadota\Http\DataTransferObjects\IndexRequestDTO;
use SchoolAid\Nadota\Http\Fields\Input;
use SchoolAid\Nadota\Http\Fields\Number;
use SchoolAid\Nadota\Http\Fields\Select;
use SchoolAid\Nadota\Http\Filters\NumberFilter;
use SchoolAid\Nadota\Http\Filters\SelectFilter;
use SchoolAid\Nadota\Http\Requests\NadotaRequest;
use SchoolAid\Nadota\Http\Services\Pipes\ApplyFiltersPipe;
use SchoolAid\Nadota\Resource;
use SchoolAid\Nadota\Tests\Fixtures\FixtureSchema;
use SchoolAid\Nadota\Tests\Fixtures\Models\Student;

beforeEach(function () {
    FixtureSchema::create();
    Student::create(['name' => 'Ana', 'age' => 8, 'status' => 'draft']);
    Student::create(['name' => 'Bob', 'age' => 10, 'status' => 'enrolled']);
    Student::create(['name' => 'Cid', 'age' => 12, 'status' => 'enrolled']);
    Student::create(['name' => 'Dee', 'age' => 15, 'status' => 'graduated']);
});

/**
 * Runs ApplyFiltersPipe for a throw-away Student resource and returns the
 * names left in the query.
 */
function applyFiltersPipeNames(array $fields, array $filters, mixed $requestFilters, bool $sendFilters = true): array
{
    $resource = new class($fields, $filters) extends Resource {
        public string $model = Student::class;

        public function __construct(private array $testFields, private array $testFilters)
        {
            parent::__construct();
        }

        public function fields(NadotaRequest $request): array
        {
            return $this->testFields;
        }

        public function filters(NadotaRequest $request): array
        {
            return $this->testFilters;
        }
    };

    $dto = new IndexRequestDTO(createNadotaRequest($sendFilters ? ['filters' => $requestFilters] : []), $resource);
    $dto->prepareQuery();

    $result = (new ApplyFiltersPipe())->handle($dto, fn ($data) => $data);

    return $result->query->orderBy('name')->pluck('name')->all();
}

// --- which filters take part ---------------------------------------------------------------

it('applies filters generated by filterable fields', function () {
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterable()], [], ['age' => '10']))->toBe(['Bob']);
});

it('applies filters declared by the resource', function () {
    expect(applyFiltersPipeNames([], [new SelectFilter('Status', 'status')], ['status' => 'enrolled']))->toBe(['Bob', 'Cid']);
});

it('combines field and resource filters with AND', function () {
    $names = applyFiltersPipeNames(
        [Number::make('Age', 'age')->filterable()],
        [new SelectFilter('Status', 'status')],
        ['age' => '12', 'status' => 'enrolled']
    );

    expect($names)->toBe(['Cid']);
});

it('ignores values for fields that are not filterable', function () {
    expect(applyFiltersPipeNames([Input::make('Name', 'name')], [], ['name' => 'Ana']))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
});

it('ignores keys no filter declares', function () {
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterable()], [], ['unknown' => 'x', 'grade_id' => 1]))
        ->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
});

it('does nothing without a filters parameter', function () {
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterable()], [], null, sendFilters: false))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
});

it('treats an empty (null) filters parameter like a missing one', function () {
    // "?filters=" reaches the pipe as null once ConvertEmptyStringsToNull has run.
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterable()], [], null))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
})->skip('ISSUE FLT-008: get("filters", []) returns the null that is present, and normalizeRangeFilters(array) throws a TypeError');

it('applies the filter of a filterable field hidden from the index', function () {
    // GET /filters lists it (flattenFields), so the index must honour it too.
    $field = Number::make('Age', 'age')->filterable()->hideFromIndex();

    expect(applyFiltersPipeNames([$field], [], ['age' => '10']))->toBe(['Bob']);
})->skip('ISSUE FLT-004: the pipe only collects filters from fieldsForIndex(), the /filters endpoint from flattenFields()');

it('ignores a malformed (non-array) filters parameter', function () {
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterable()], [], 'age=10'))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
})->skip('ISSUE FLT-008: normalizeRangeFilters(array $requestFilters) throws a TypeError for a string');

// --- range normalisation -------------------------------------------------------------------

it('turns {key}_from / {key}_to into a start/end range', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range()];

    expect(applyFiltersPipeNames([], $filters, ['age_from' => '10', 'age_to' => '12']))->toBe(['Bob', 'Cid']);
});

it('normalises a range with only one side', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range()];

    expect(applyFiltersPipeNames([], $filters, ['age_from' => '12']))->toBe(['Cid', 'Dee'])
        ->and(applyFiltersPipeNames([], $filters, ['age_to' => '10']))->toBe(['Ana', 'Bob']);
});

it('normalises the range keys of a field made filterableRange()', function () {
    expect(applyFiltersPipeNames([Number::make('Age', 'age')->filterableRange()], [], ['age_from' => '9', 'age_to' => '12']))
        ->toBe(['Bob', 'Cid']);
});

it('skips a range whose two sides are null', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range()];

    expect(applyFiltersPipeNames([], $filters, ['age_from' => null, 'age_to' => null]))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
});

it('only reaches a range filter through its _from/_to keys (a plain value is dropped)', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range()];

    expect(applyFiltersPipeNames([], $filters, ['age' => '10']))->toBe(['Ana', 'Bob', 'Cid', 'Dee'])
        ->and(applyFiltersPipeNames([], $filters, ['age' => ['start' => '10', 'end' => '12']]))->toBe(['Ana', 'Bob', 'Cid', 'Dee']);
});

it('accepts the nested filters[key][from|to] format the API docs describe', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range()];

    expect(applyFiltersPipeNames([], $filters, ['age' => ['from' => '10', 'to' => '12']]))->toBe(['Bob', 'Cid']);
})->skip('ISSUE FLT-002: docs/api/filtering.md documents filters[key][from]; the pipe only reads filters[key_from]');

it('keeps non-range values next to normalised ranges', function () {
    $filters = [NumberFilter::make('Age Range', 'age')->range(), new SelectFilter('Status', 'status')];

    expect(applyFiltersPipeNames([], $filters, ['age_from' => '9', 'status' => 'enrolled']))->toBe(['Bob', 'Cid']);
});

// --- key collisions (StudentResource declares both) ---------------------------------------

it('lets the exact field filter handle a plain value when a range filter shares its key', function () {
    $names = applyFiltersPipeNames(
        [Number::make('Age', 'age')->filterable()],
        [NumberFilter::make('Age Range', 'age')->range()],
        ['age' => '12']
    );

    expect($names)->toBe(['Cid']);
});

it('applies the range filter when a field filter shares its key', function () {
    $names = applyFiltersPipeNames(
        [Number::make('Age', 'age')->filterable()],
        [NumberFilter::make('Age Range', 'age')->range()],
        ['age_from' => '10', 'age_to' => '12']
    );

    expect($names)->toBe(['Bob', 'Cid']);
})->skip('ISSUE FLT-001: the {start,end} array is stored under "age" and FilterCriteria hands it to the first "age" filter (the exact one), i.e. age = 10');

it('applies both the exact value and the range when both are sent for a shared key', function () {
    $names = applyFiltersPipeNames(
        [Number::make('Age', 'age')->filterable()],
        [NumberFilter::make('Age Range', 'age')->range()],
        ['age' => '15', 'age_from' => '10']
    );

    expect($names)->toBe(['Dee']);
})->skip('ISSUE FLT-001: the normalised range overwrites the exact value under the same key');

it('applies only one of two select filters that share a key', function () {
    // Field Select (value => label) and resource SelectFilter on the same column: only the first runs.
    $names = applyFiltersPipeNames(
        [Select::make('Status', 'status')->options(['draft' => 'Draft', 'enrolled' => 'Enrolled'])->filterable()],
        [new SelectFilter('Status Filter', 'status')],
        ['status' => 'graduated']
    );

    expect($names)->toBe(['Dee']);
});
